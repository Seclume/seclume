package space.seclume.r2dbc;

import java.io.IOException;
import java.net.InetSocketAddress;
import java.net.Socket;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.BeforeAll;
import org.springframework.jdbc.core.JdbcOperations;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SimpleDriverDataSource;

import io.r2dbc.spi.ConnectionFactories;
import io.r2dbc.spi.ConnectionFactory;
import io.r2dbc.spi.test.TestKit;
import space.seclume.tck.TestHosts;

/**
 * R2DBC TCK ({@code r2dbc-spi-test}) against seclume on Oracle.
 */
class R2dbcTckOnOracleTest implements TestKit<String> {

    private static final String HOST = System.getProperty("seclume.oracle.host", TestHosts.database());
    private static final int PORT = Integer.getInteger("seclume.oracle.port", 1521);

    private static ConnectionFactory factory;
    private static JdbcOperations jdbc;

    @BeforeAll
    static void server() throws Exception {
        Path password = null;
        for (Path candidate : List.of(Path.of(".local-oracle-password"),
                Path.of("..", ".local-oracle-password"))) {
            if (Files.exists(candidate)) {
                password = candidate.toAbsolutePath().normalize();
            }
        }
        Assumptions.assumeTrue(password != null, "no .local-oracle-password");
        try (Socket probe = new Socket()) {
            probe.connect(new InetSocketAddress(HOST, PORT), 2000);
        } catch (IOException e) {
            Assumptions.abort("no Oracle on " + HOST + ":" + PORT);
        }
        String path = password.toString().replace('\\', '/');
        factory = ConnectionFactories.get("r2dbc:seclume:oracle://seclume_test@" + HOST + ":"
                + PORT + "/FREEPDB1?provider=file&path=" + path);
        jdbc = new JdbcTemplate(new SimpleDriverDataSource(
                new space.seclume.oracle.jdbc.OraDriver(),
                "jdbc:seclume:oracle://" + HOST + ":" + PORT + "/FREEPDB1?user=seclume_test"
                        + "&provider=file&path=" + path));
    }

    @Override
    public ConnectionFactory getConnectionFactory() {
        return factory;
    }

    @Override
    public String getPlaceholder(int index) {
        return ":p" + index;
    }

    @Override
    public String getIdentifier(int index) {
        return "p" + index;
    }

    @Override
    public JdbcOperations getJdbcOperations() {
        return jdbc;
    }

    @Override
    @SuppressWarnings("deprecation")
    public String getCreateTableWithAutogeneratedKey() {
        return "CREATE TABLE test (id NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY, test_value NUMBER)";
    }

    @Override
    public String blobType() {
        return "BLOB";
    }

    @Override
    public String clobType() {
        return "CLOB";
    }

    /** The kit's insert names no column, and an identity column cannot take the 100. */
    @Override
    public String doGetSql(TestStatement statement) {
        return switch (statement) {
            case INSERT_VALUE_AUTOGENERATED_KEY -> "INSERT INTO test (test_value) VALUES (100)";
            // Oracle folds an unquoted alias to upper case and reports it so;
            // quoted, it stays as written - what the kit's case looks for.
            case SELECT_VALUE_ALIASED_COLUMNS ->
                    "SELECT col1 AS \"b\", col1 AS \"c\", col1 AS \"a\" FROM test_two_column";
            default -> statement.getSql();
        };
    }

    /**
     * Oracle hands every NUMBER out as a BigDecimal - as ojdbc and
     * oracle-r2dbc do - and the kit compares with an Integer.
     */
    @Override
    public Object extractColumn(io.r2dbc.spi.Row row) {
        return integral(row.get("test_value"));
    }

    private static Object integral(Object value) {
        return value instanceof java.math.BigDecimal number ? number.intValueExact() : value;
    }

    /** The kit's case, with the NUMBER read as a number - see extractColumn. */
    @Override
    @org.junit.jupiter.api.Test
    public void duplicateColumnNames() {
        getJdbcOperations().execute(expand(TestStatement.INSERT_TWO_COLUMNS));
        reactor.core.publisher.Flux.usingWhen(getConnectionFactory().create(),
                        connection -> reactor.core.publisher.Flux.from(connection
                                        .createStatement(expand(TestStatement.SELECT_VALUE_TWO_COLUMNS))
                                        .execute())
                                .flatMap(result -> result.map((row, meta) -> java.util.Arrays.asList(
                                        integral(row.get("test_value")),
                                        integral(row.get("TEST_VALUE")))))
                                .flatMapIterable(java.util.function.Function.identity()),
                        io.r2dbc.spi.Connection::close)
                .as(reactor.test.StepVerifier::create)
                .expectNext(100).as("test_value from col1")
                .expectNext(100).as("test_value from col1 (upper case)")
                .verifyComplete();
    }

    /**
     * Oracle runs one statement per call and has no text of several: the server answers ORA-03405. The kit's case expects two results; this one holds the
     * driver to refusing the text with an R2DBC exception rather than running
     * part of it.
     */
    @Override
    @org.junit.jupiter.api.Test
    public void compoundStatement() {
        getJdbcOperations().execute(expand(TestStatement.INSERT_VALUE100));
        reactor.core.publisher.Flux.usingWhen(getConnectionFactory().create(),
                        connection -> reactor.core.publisher.Flux.from(connection
                                        .createStatement(expand(TestStatement.SELECT_VALUE_BATCH))
                                        .execute())
                                .flatMap(result -> result.map((row, meta) -> row.get(0))),
                        io.r2dbc.spi.Connection::close)
                .as(reactor.test.StepVerifier::create)
                .expectError(io.r2dbc.spi.R2dbcException.class)
                .verify();
    }

    /**
     * Oracle returns keys only for the columns it is told, and the driver
     * says so rather than guess: returnGeneratedValues() without a name is
     * refused with that explanation. This is the kit's case with the key
     * named, which is the way generated keys work here.
     */
    @Override
    @org.junit.jupiter.api.Test
    @SuppressWarnings("deprecation")
    public void returnGeneratedValues() {
        getJdbcOperations().execute(expand(TestStatement.DROP_TABLE));
        getJdbcOperations().execute(getCreateTableWithAutogeneratedKey());
        reactor.core.publisher.Flux.usingWhen(getConnectionFactory().create(),
                        connection -> reactor.core.publisher.Flux.from(connection
                                        .createStatement(expand(TestStatement.INSERT_VALUE_AUTOGENERATED_KEY))
                                        .returnGeneratedValues("id")
                                        .execute())
                                .flatMap(result -> result.map((row, meta) -> row.get(0))),
                        io.r2dbc.spi.Connection::close)
                .as(reactor.test.StepVerifier::create)
                .expectNextCount(1)
                .verifyComplete();
    }
}
