package space.seclume.r2dbc;

import java.io.IOException;
import java.net.InetSocketAddress;
import java.net.Socket;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.BeforeAll;
import org.springframework.jdbc.core.JdbcOperations;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SimpleDriverDataSource;

import io.r2dbc.spi.ConnectionFactories;
import io.r2dbc.spi.ConnectionFactory;
import io.r2dbc.spi.test.TestKit;
import space.seclume.tck.TestHosts;

/**
 * R2DBC's own conformance suite ({@code r2dbc-spi-test}) against seclume on
 * PostgreSQL - the same suite the vendor drivers are measured with. The
 * tables it needs are made through seclume's JDBC driver.
 */
class R2dbcTckOnPostgresTest implements TestKit<String> {

    private static final String HOST = System.getProperty("seclume.pgtls.host", TestHosts.database());
    private static final int PORT = Integer.getInteger("seclume.pgtls.port", 5433);

    private static ConnectionFactory factory;
    private static JdbcOperations jdbc;

    @BeforeAll
    static void server() throws Exception {
        Path password = null;
        for (Path candidate : List.of(Path.of(".local-pgtls-password"),
                Path.of("..", ".local-pgtls-password"))) {
            if (Files.exists(candidate)) {
                password = candidate.toAbsolutePath().normalize();
            }
        }
        Assumptions.assumeTrue(password != null, "no .local-pgtls-password");
        try (Socket probe = new Socket()) {
            probe.connect(new InetSocketAddress(HOST, PORT), 2000);
        } catch (IOException e) {
            Assumptions.abort("no PostgreSQL on " + HOST + ":" + PORT);
        }
        String path = password.toString().replace('\\', '/');
        factory = ConnectionFactories.get("r2dbc:seclume:postgresql://seclume_test@" + HOST + ":"
                + PORT + "/seclume_test?provider=file&path=" + path
                + "&options=trustServerCertificate%3Dtrue");
        jdbc = new JdbcTemplate(new SimpleDriverDataSource(
                new space.seclume.postgresql.jdbc.SeclumeDriver(),
                "jdbc:seclume:postgresql://" + HOST + ":" + PORT + "/seclume_test?user=seclume_test"
                        + "&provider=file&path=" + path + "&trustServerCertificate=true"));
    }

    @Override
    public ConnectionFactory getConnectionFactory() {
        return factory;
    }

    @Override
    public String getPlaceholder(int index) {
        return "$" + (index + 1);
    }

    @Override
    public String getIdentifier(int index) {
        return getPlaceholder(index);
    }

    @Override
    public JdbcOperations getJdbcOperations() {
        return jdbc;
    }

    /** Deprecated in the suite, but its default is not PostgreSQL's SQL. */
    @Override
    @SuppressWarnings("deprecation")
    public String getCreateTableWithAutogeneratedKey() {
        return "CREATE TABLE test (id SERIAL PRIMARY KEY, test_value INTEGER)";
    }

    @Override
    public String blobType() {
        return "BYTEA";
    }

    @Override
    public String clobType() {
        return "TEXT";
    }
}
