package space.seclume.r2dbc;

import java.io.IOException;
import java.net.InetSocketAddress;
import java.net.Socket;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.BeforeAll;
import org.springframework.jdbc.core.JdbcOperations;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SimpleDriverDataSource;

import io.r2dbc.spi.ConnectionFactories;
import io.r2dbc.spi.ConnectionFactory;
import io.r2dbc.spi.test.TestKit;
import space.seclume.tck.TestHosts;

/**
 * R2DBC TCK ({@code r2dbc-spi-test}) against seclume on SQL Server.
 */
class R2dbcTckOnSqlServerTest implements TestKit<String> {

    private static final String HOST = System.getProperty("seclume.sqlserver.host", TestHosts.database());
    private static final int PORT = Integer.getInteger("seclume.sqlserver.port", 1433);

    private static ConnectionFactory factory;
    private static JdbcOperations jdbc;

    @BeforeAll
    static void server() throws Exception {
        Path password = null;
        for (Path candidate : List.of(Path.of(".local-mssql-password"),
                Path.of("..", ".local-mssql-password"))) {
            if (Files.exists(candidate)) {
                password = candidate.toAbsolutePath().normalize();
            }
        }
        Assumptions.assumeTrue(password != null, "no .local-mssql-password");
        try (Socket probe = new Socket()) {
            probe.connect(new InetSocketAddress(HOST, PORT), 2000);
        } catch (IOException e) {
            Assumptions.abort("no SQL Server on " + HOST + ":" + PORT);
        }
        String path = password.toString().replace('\\', '/');
        factory = ConnectionFactories.get("r2dbc:seclume:sqlserver://sa@" + HOST + ":"
                + PORT + "/master?provider=file&path=" + path
                + "&trustServerCertificate=true");
        jdbc = new JdbcTemplate(new SimpleDriverDataSource(
                new space.seclume.sqlserver.jdbc.TdsDriver(),
                "jdbc:seclume:sqlserver://" + HOST + ":" + PORT + "/master?user=sa"
                        + "&provider=file&path=" + path + "&trustServerCertificate=true"));
    }

    @Override
    public ConnectionFactory getConnectionFactory() {
        return factory;
    }

    @Override
    public String getPlaceholder(int index) {
        return "@P" + index;
    }

    @Override
    public String getIdentifier(int index) {
        return "P" + index;
    }

    @Override
    public JdbcOperations getJdbcOperations() {
        return jdbc;
    }

    @Override
    @SuppressWarnings("deprecation")
    public String getCreateTableWithAutogeneratedKey() {
        return "CREATE TABLE test (id INT IDENTITY PRIMARY KEY, test_value INTEGER)";
    }

    @Override
    public String blobType() {
        return "VARBINARY(MAX)";
    }

    @Override
    public String clobType() {
        return "VARCHAR(MAX)";
    }
}
