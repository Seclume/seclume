    /**
     * Auto-commit has to commit - and switching it off has to hold back.
     *
     * <p>Read over a <b>second</b> connection, because that is the only way to
     * tell a commit from a write that is merely visible to its own session.
     * This is the test for a bug that lost data quietly: the driver reported
     * auto-commit as on, as JDBC requires, and never set the bit that makes
     * Oracle commit - so everything an application wrote without calling
     * {@code commit} itself was rolled back when the connection closed.
     */
    @Test
    void autoCommitCommitsAndTurningItOffHoldsBack() throws Exception {
        try (Connection writer = connect()) {
            try (Statement statement = writer.createStatement()) {
                statement.execute("create table zl_commit (n number(9))");
            }
            try {
                try (PreparedStatement insert = writer.prepareStatement(
                        "insert into zl_commit values (?)")) {
                    insert.setInt(1, 1);
                    insert.executeUpdate();              // auto-commit is on
                }
                assertEquals(1, countOver(1), "auto-commit did not commit");

                writer.setAutoCommit(false);
                try (PreparedStatement insert = writer.prepareStatement(
                        "insert into zl_commit values (?)")) {
                    insert.setInt(1, 2);
                    insert.executeUpdate();
                }
                assertEquals(1, countOver(2),
                        "a row appeared although the transaction was still open");
                writer.commit();
                assertEquals(2, countOver(2), "commit did not commit");

                try (PreparedStatement insert = writer.prepareStatement(
                        "insert into zl_commit values (?)")) {
                    insert.setInt(1, 3);
                    insert.executeUpdate();
                }
                writer.rollback();
                assertEquals(2, countOver(3), "rollback did not roll back");
            } finally {
                writer.setAutoCommit(true);
                try (Statement statement = writer.createStatement()) {
                    statement.execute("drop table zl_commit");
                }
            }
        }
    }

    /** How many rows a <b>different</b> connection can see. */
    private static int countOver(int ignored) throws SQLException {
        try (Connection reader = connect();
             Statement statement = reader.createStatement();
             ResultSet found = statement.executeQuery("select count(*) from zl_commit")) {
            found.next();
            return found.getInt(1);
        }
    }

    /**
     * A batch as one call, and many executions on one cursor.
     *
     * <p>Two things are checked here that used to be broken in opposite ways.
     * The batch goes over as a <b>single</b> array execution - the statement
     * once, the values five hundred times - instead of five hundred round
     * trips. And every execution used to have the server parse the text anew,
     * which opens a <b>new cursor</b> each time: after a few hundred the
     * connection died with {@code ORA-01000, maximum open cursors exceeded}.
     * The four hundred queries in the second half are there to make that come
     * back if the cursor is ever forgotten again.
     */
    @Test
    void runsABatchAsOneCallAndKeepsOneCursor() throws Exception {
        int rows = 500;
        try (Connection connection = connect()) {
            try (Statement statement = connection.createStatement()) {
                statement.execute("create table zl_array (n number(9), t varchar2(40))");
            }
            try {
                try (PreparedStatement insert = connection.prepareStatement(
                        "insert into zl_array (n, t) values (?, ?)")) {
                    for (int i = 0; i < rows; i++) {
                        insert.setInt(1, i);
                        insert.setString(2, "row-" + i);
                        insert.addBatch();
                    }
                    int[] counts = insert.executeBatch();
                    assertEquals(rows, counts.length, "one count per row");
                    for (int count : counts) {
                        assertEquals(1, count);
                    }
                }
                connection.commit();
                try (Statement statement = connection.createStatement();
                     ResultSet found = statement.executeQuery(
                             "select count(*), min(t), max(n) from zl_array")) {
                    assertTrue(found.next());
                    assertEquals(rows, found.getInt(1));
                    assertEquals("row-0", found.getString(2));
                    assertEquals(rows - 1, found.getInt(3));
                }

                // Well past the default open_cursors of 300.
                try (PreparedStatement query = connection.prepareStatement(
                        "select count(*) from zl_array where n > ?")) {
                    for (int i = 0; i < 400; i++) {
                        query.setInt(1, i);
                        try (ResultSet found = query.executeQuery()) {
                            assertTrue(found.next());
                            assertEquals(rows - i - 1, found.getInt(1));
                        }
                    }
                }
            } finally {
                try (Statement statement = connection.createStatement()) {
                    statement.execute("drop table zl_array");
                }
            }
        }
    }

    /**
     * Bind variables, end to end: types in, types out, and the counts the
     * server reports for a statement that changes rows.
     *
     * <p>Oracle needs no separate prepare call - the text and the values
     * travel in one message - so this costs no round trip more than a plain
     * statement, and no value ever enters the statement text.
     */
    @Test
    void runsPreparedStatements() throws Exception {
        try (Connection connection = connect()) {
            try (Statement statement = connection.createStatement()) {
                statement.execute("create table zl_prepared (n number(9), t varchar2(40), "
                        + "d date, r raw(8))");
            }
            try {
                try (PreparedStatement insert = connection.prepareStatement(
                        "insert into zl_prepared (n, t, d, r) values (?, ?, ?, ?)")) {
                    insert.setInt(1, 1);
                    // A question mark inside a literal is text, and so is the
                    // apostrophe doubled in front of it. Both go through the
                    // rewriter, and neither becomes a bind variable.
                    insert.setString(2, "it's a test? yes");
                    insert.setDate(3, java.sql.Date.valueOf("2026-09-08"));
                    insert.setBytes(4, new byte[] {1, 2, 3});
                    assertEquals(1, insert.executeUpdate(), "the server counts the row");

                    insert.setInt(1, 2);
                    insert.setString(2, null);
                    insert.setNull(3, Types.DATE);
                    insert.setNull(4, Types.VARBINARY);
                    assertEquals(1, insert.executeUpdate());
                }
                try (PreparedStatement batch = connection.prepareStatement(
                        "insert into zl_prepared (n, t) values (?, ?)")) {
                    for (int i = 10; i < 14; i++) {
                        batch.setInt(1, i);
                        batch.setString(2, "row" + i);
                        batch.addBatch();
                    }
                    assertArrayEquals(new int[] {1, 1, 1, 1}, batch.executeBatch());
                }
                connection.commit();

                try (PreparedStatement select = connection.prepareStatement(
                        "select n, t, d, r from zl_prepared where n <= ? order by n")) {
                    select.setInt(1, 2);
                    try (ResultSet rows = select.executeQuery()) {
                        assertTrue(rows.next());
                        assertEquals(1, rows.getInt("n"));
                        assertEquals("it's a test? yes", rows.getString("t"));
                        assertEquals(java.sql.Date.valueOf("2026-09-08"), rows.getDate("d"));
                        assertArrayEquals(new byte[] {1, 2, 3}, rows.getBytes("r"));

                        assertTrue(rows.next());
                        assertEquals(2, rows.getInt("n"));
                        assertNull(rows.getString("t"));
                        assertNull(rows.getDate("d"));
                        assertFalse(rows.next());
                    }
                }
                try (PreparedStatement update = connection.prepareStatement(
                        "update zl_prepared set t = ? where n = ?")) {
                    update.setString(1, "one");
                    update.setInt(2, 1);
                    assertEquals(1, update.executeUpdate());
                }
                try (PreparedStatement delete = connection.prepareStatement(
                        "delete from zl_prepared where n = ?")) {
                    delete.setInt(1, 2);
                    assertEquals(1, delete.executeUpdate());
                }
                connection.commit();
                try (Statement statement = connection.createStatement();
                     ResultSet count = statement.executeQuery(
                             "select count(*) from zl_prepared")) {
                    assertTrue(count.next());
                    assertEquals(5, count.getInt(1));
                }
            } finally {
                try (Statement statement = connection.createStatement()) {
                    statement.execute("drop table zl_prepared");
                }
            }
        }
    }

