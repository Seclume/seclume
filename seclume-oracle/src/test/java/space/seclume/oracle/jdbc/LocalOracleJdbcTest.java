    /** Drops a table if it is there - Oracle has no "if exists". */
    private static void drop(Connection connection, String table) {
        try (Statement statement = connection.createStatement()) {
            statement.execute("drop table " + table + " purge");   // purge: sonst zaehlt Oracle sie weiter
        } catch (SQLException e) {
            // ORA-00942: it was not there, which is what was wanted.
        }
    }

    /**
     * Generated keys - what every {@code @GeneratedValue} entity needs.
     *
     * <p>Oracle has no separate channel for them: the statement has to say
     * {@code returning <column> into :n}, and the value arrives in that bind.
     * The driver adds the clause and one output bind per column, and reads
     * what comes back in front of the answer - a {@code ROW_DATA} message
     * without any column description, whose shape is known only because the
     * driver chose the clause itself. All of it taken from a capture of the
     * reference client, not from guessing.
     */
    @Test
    void generatedKeysComeBackFromAnInsert() throws Exception {
        try (Connection connection = connect()) {
            drop(connection, "zl_keys");
            try (Statement statement = connection.createStatement()) {
                statement.execute("create table zl_keys ("
                        + "id number generated by default as identity primary key, "
                        + "name varchar2(50))");
            }
            try {
                try (PreparedStatement insert = connection.prepareStatement(
                        "insert into zl_keys (name) values (?)", new String[] {"id"})) {
                    insert.setString(1, "first");
                    assertEquals(1, insert.executeUpdate());
                    long first;
                    try (ResultSet keys = insert.getGeneratedKeys()) {
                        assertTrue(keys.next(), "no key came back");
                        first = keys.getLong(1);
                        assertTrue(first > 0, "the key was " + first);
                    }

                    insert.setString(1, "second");
                    insert.executeUpdate();
                    try (ResultSet keys = insert.getGeneratedKeys()) {
                        assertTrue(keys.next());
                        assertEquals(first + 1, keys.getLong("id"),
                                "the second key does not follow the first");
                    }
                }
            } finally {
                drop(connection, "zl_keys");
            }
        }
    }

